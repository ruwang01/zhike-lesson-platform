/** 未知课型（管理员自建）按综合课范式处理 */
export function shapeOf(courseType) {
  const code = String(courseType?.code || '').toLowerCase();
  if (SHAPES[code]) return SHAPES[code];
  const name = String(courseType?.name || '');
  if (/听说|听力|口语/.test(name)) return LISTENING;
  if (/读写|阅读|写作/.test(name)) return READING;
  return COMPREHENSIVE;
}

/** 供提示词用的范式摘要（不含实现细节） */
export function shapeBrief(shape) {
  return {
    课型: shape.name,
    参考来源: shape.reference,
    有参考范本: shape.hasReference,
    目标领域: shape.objectiveDomains.map((d) => d.key),
    环节序列: shape.stageGuide.map((s) => ({
      环节: s.name,
      时间占比: `${Math.round(s.ratio * 100)}%`,
      必做: s.must,
      要点: s.note,
    })),
    教学步骤栏位: shape.stageColumns,
  };
}
